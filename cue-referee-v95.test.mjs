import assert from 'node:assert/strict';
import {initialReferee,adjudicate,placeCueBall,respotColours} from './cue-referee-v95.js';
const balls=(list)=>list.map(([number,live=true])=>({number,live,x:150+number*35,y:200}));
const shot=(firstHit,potted=[],cushion=true)=>({firstHit,potted,events:cushion?[{type:'first-contact',step:2},{type:'cushion',step:3}]:[]});
let s=initialReferee('pool');
s=adjudicate(s,balls([[0],[1],[8],[9]]),shot(1,[1]),balls([[0],[1,false],[8],[9]]));
assert.equal(s.groups[0],null,'groups remain open on break');
assert.equal(s.turn,1,'break pot does not assign group in simplified referee');
s=adjudicate(s,balls([[0],[1],[8],[9]]),shot(9,[9]),balls([[0],[1],[8],[9,false]]));
assert.equal(s.groups[1],'stripes');
assert.equal(s.turn,1);
let f=adjudicate({...s,turn:1},balls([[0],[1],[8],[9]]),shot(1,[]),balls([[0],[1],[8],[9]]));
assert.equal(f.ballInHand,true);assert.equal(f.turn,0);
let e=adjudicate({...s,turn:1,groups:['solids','stripes']},balls([[0],[1],[8],[9,false]]),shot(8,[8]),balls([[0],[1],[8,false],[9,false]]));
assert.equal(e.finished,true);assert.equal(e.winner,1);
e=adjudicate({...s,turn:1,groups:['solids','stripes']},balls([[0],[1],[8],[9]]),shot(8,[8]),balls([[0],[1],[8,false],[9]]));
assert.equal(e.winner,0);
let n=initialReferee('snooker');
n=adjudicate(n,balls([[0],[1],[2]]),shot(1,[1]),balls([[0],[1,false],[2]]));
assert.equal(n.phase,'colour');assert.equal(n.scores[0],1);
n=adjudicate(n,balls([[0],[2]]),shot(2,[2]),balls([[0],[2,false]]));
assert.equal(n.phase,'clear');assert.equal(n.scores[0],3);
n=adjudicate(n,balls([[0],[2]]),shot(7,[]),balls([[0],[2]]));
assert.equal(n.scores[1],7);assert.equal(n.turn,1);
const cue=balls([[0,false],[1]]);assert.equal(placeCueBall(cue),true);assert.equal(cue[0].live,true);
const cols=balls([[0],[2,false]]);respotColours(cols);assert.equal(cols[1].live,true);
console.log('11 referee scenarios passed');
